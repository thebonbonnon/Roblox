--[[
	Builds unit models from ReplicatedStorage.Shared.ModelSpecs (generated by tools/gen_models.py).

	Drop-in replacements: put a Model with the same name (e.g. "Tower", "Hero_Knight",
	"Minion_melee", "Tree") in ServerStorage.Models or ReplicatedStorage.Models and it is used
	instead. It is scaled to the built-in model's height, any scripts inside are removed, and
	parts whose names start with "Team" are recolored to the team color.

	Usage:
	  local model, root, info = ModelFactory.build("Tower", {
	      team = "Blue", cframe = CFrame.new(x, groundY, z), static = true, parent = folder })
	  info.rootY      root part height above the ground point
	  info.barHeight  health bar offset above the root
	  info.fire       part that projectiles are fired from (if the spec names one)
	  info.humanoid   the rig's Humanoid (R6 heroes only)

	Heroes are real R6 rigs: HumanoidRootPart (anchored, moved by the server) -> RootJoint ->
	Torso -> Neck / shoulders / hips, using the standard R6 joint frames so Roblox's R6 animations
	play correctly. Gear parts are welded to the limb named in their spec "attach" field.
	ModelFactory.attachGear puts the same gear on a player's R6 character.
]]
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local ServerStorage = game:GetService("ServerStorage")

local Config = require(ReplicatedStorage.Shared.Config)
local Specs = require(ReplicatedStorage.Shared.ModelSpecs)

local ModelFactory = {}

local BLACK = Color3.new(0, 0, 0)
local WHITE = Color3.new(1, 1, 1)

local function resolveColor(c, team)
	if type(c) == "table" then
		return Color3.fromRGB(c[1], c[2], c[3])
	end
	local base = Config.TeamColors[team] or Color3.fromRGB(200, 200, 200)
	if c == "teamDark" then
		return base:Lerp(BLACK, 0.4)
	elseif c == "teamLight" then
		return base:Lerp(WHITE, 0.35)
	end
	return base
end

local function localCFrame(p, scale)
	local pos = p.pos
	local cf = CFrame.new(pos[1] * scale, pos[2] * scale, pos[3] * scale)
	local rot = p.rot
	if rot then
		cf *= CFrame.Angles(math.rad(rot[1]), math.rad(rot[2]), math.rad(rot[3]))
	end
	if p.shape == "cyl" then
		-- Roblox cylinders run along X; specs describe them standing up.
		cf *= CFrame.Angles(0, 0, math.rad(90))
	end
	return cf
end

local function partSize(p, scale)
	local s = p.size
	if p.shape == "ball" then
		return Vector3.one * s[1] * scale
	elseif p.shape == "cyl" then
		return Vector3.new(s[1], s[2], s[2]) * scale
	end
	return Vector3.new(s[1], s[2], s[3]) * scale
end

local function makePart(p, team, cframe, scale)
	local part = Instance.new(p.shape == "wedge" and "WedgePart" or "Part")
	if p.shape == "ball" then
		part.Shape = Enum.PartType.Ball
	elseif p.shape == "cyl" then
		part.Shape = Enum.PartType.Cylinder
	end
	part.Name = p.name
	part.Size = partSize(p, scale)
	part.CFrame = cframe
	part.Color = resolveColor(p.color, team)
	part.Material = Enum.Material[p.material] or Enum.Material.SmoothPlastic
	part.Transparency = p.alpha or 0
	part.TopSurface = Enum.SurfaceType.Smooth
	part.BottomSurface = Enum.SurfaceType.Smooth
	part.CastShadow = (p.alpha or 0) < 0.5
	part.CanCollide = p.collide == true
	part.CanTouch = false
	if p.shape == "head" then
		local mesh = Instance.new("SpecialMesh")
		mesh.MeshType = Enum.MeshType.Head
		mesh.Scale = Vector3.one * 1.25
		mesh.Parent = part
	end
	return part
end

local function weld(root, part)
	local w = Instance.new("WeldConstraint")
	w.Part0 = root
	w.Part1 = part
	w.Parent = part
end

local function findCustom(name)
	for _, container in ipairs({ ServerStorage, ReplicatedStorage }) do
		local folder = container:FindFirstChild("Models")
		local m = folder and folder:FindFirstChild(name)
		if m and m:IsA("Model") then
			return m
		end
	end
	return nil
end

local function buildFromSpec(spec, opts, scale)
	local model = Instance.new("Model")
	local root, fire
	local parts = {}
	for _, p in ipairs(spec.parts) do
		local part = makePart(p, opts.team, opts.cframe * localCFrame(p, scale), scale)
		part.Parent = model
		parts[#parts + 1] = part
		if p.name == spec.root then
			root = part
		end
		if p.name == spec.fire then
			fire = part
		end
	end
	return model, root, fire, parts
end

local function buildFromCustom(template, spec, opts, scale)
	local model = template:Clone()
	for _, d in ipairs(model:GetDescendants()) do
		if d:IsA("LuaSourceContainer") then
			d:Destroy() -- never run scripts that came with a free model
		elseif d:IsA("Humanoid") then
			d.DisplayDistanceType = Enum.HumanoidDisplayDistanceType.None
			d.HealthDisplayType = Enum.HumanoidHealthDisplayType.AlwaysOff
		end
	end

	-- Scale to the built-in model's height and stand it on the ground point.
	local _, size = model:GetBoundingBox()
	if size.Y > 0.01 then
		model:ScaleTo(model:GetScale() * (spec.height * scale) / size.Y)
	end
	local bbox, newSize = model:GetBoundingBox()
	local bottom = CFrame.new(bbox.Position - Vector3.new(0, newSize.Y / 2, 0))
	model:PivotTo(opts.cframe * bottom:ToObjectSpace(model:GetPivot()))

	local parts = {}
	for _, d in ipairs(model:GetDescendants()) do
		if d:IsA("BasePart") then
			if string.sub(d.Name, 1, 4) == "Team" then
				d.Color = Config.TeamColors[opts.team] or d.Color
			end
			if not opts.static then
				d.CanCollide = false
			end
			d.CanTouch = false
			parts[#parts + 1] = d
		end
	end

	-- Invisible root with the built-in model's size and position keeps gameplay identical.
	local rootSpec, fireSpec
	for _, p in ipairs(spec.parts) do
		if p.name == spec.root then
			rootSpec = p
		end
		if p.name == spec.fire then
			fireSpec = p
		end
	end
	local function invisible(name, p, collide)
		local part = Instance.new("Part")
		part.Name = name
		part.Size = partSize(p, scale)
		part.Shape = p.shape == "ball" and Enum.PartType.Ball or Enum.PartType.Block
		part.CFrame = opts.cframe * localCFrame(p, scale)
		part.Transparency = 1
		part.CanCollide = collide
		part.CanTouch = false
		part.CastShadow = false
		part.Parent = model
		parts[#parts + 1] = part
		return part
	end
	local root = invisible("Root", rootSpec, rootSpec.collide == true)
	local fire = fireSpec and invisible("FirePoint", fireSpec, false) or nil
	return model, root, fire, parts
end

